// Generates src/generated/agent-config.ts (zod) from ../agent_config.schema.json.
// The zod schema is for types and API-response parsing only. Config validation is done by the
// API (`POST /agent-configs/validate` → vp_shared.validate_agent_config), never in TypeScript.
import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

import $RefParser from "@apidevtools/json-schema-ref-parser";
import { jsonSchemaToZod } from "json-schema-to-zod";
import { format } from "prettier";

const schemaPath = fileURLToPath(new URL("../../agent_config.schema.json", import.meta.url));
const outPath = fileURLToPath(new URL("../src/generated/agent-config.ts", import.meta.url));

// json-schema-to-zod does not follow $ref; the schema has no cycles, so inline everything.
const schema = await $RefParser.dereference(schemaPath);
delete schema.$defs;
// The voice anyOf only says which keys are required ("preset, or all of stt/llm/tts"). zod output
// for it is `.and(z.union([z.any(), z.any()]))`, which erases the voice type. The API enforces it.
delete schema.properties.voice.anyOf;

const body = jsonSchemaToZod(schema, {
  module: "esm",
  name: "agentConfigSchema",
  type: "AgentConfig",
});

const header =
  "// Generated by `pnpm codegen` from packages/shared/agent_config.schema.json. Do not edit.\n" +
  "// For types and parsing only; validate configs via the API (POST /agent-configs/validate).\n";

await writeFile(outPath, await format(header + body, { parser: "typescript", printWidth: 100 }));
