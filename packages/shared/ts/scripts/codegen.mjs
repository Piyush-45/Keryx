// Generates zod schemas in src/generated/ from packages/shared/*.schema.json.
// The zod schemas are for types and parsing only. Agent configs are validated by the API
// (`POST /agent-configs/validate` → vp_shared.validate_agent_config), never in TypeScript.
import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

import $RefParser from "@apidevtools/json-schema-ref-parser";
import { jsonSchemaToZod } from "json-schema-to-zod";
import { format } from "prettier";

const TARGETS = [
  { schema: "agent_config.schema.json", out: "agent-config.ts", name: "agentConfigSchema", type: "AgentConfig" },
  { schema: "events.schema.json", out: "events.ts", name: "callEventSchema", type: "CallEvent" },
];

// An anyOf whose branches only list required keys (e.g. voice: "preset, or all of stt/llm/tts")
// becomes `.and(z.union([z.any(), z.any()]))` in zod, which erases the parent's type. The
// server-side validator enforces these rules, so drop them here.
const isConstraintOnly = (branch) =>
  !("type" in branch || "$ref" in branch || "const" in branch || "enum" in branch || "anyOf" in branch);

function stripConstraintOnlyAnyOf(node) {
  if (Array.isArray(node)) return node.forEach(stripConstraintOnlyAnyOf);
  if (node === null || typeof node !== "object") return;
  if (Array.isArray(node.anyOf) && node.type === "object" && node.anyOf.every(isConstraintOnly)) {
    delete node.anyOf;
  }
  Object.values(node).forEach(stripConstraintOnlyAnyOf);
}

for (const target of TARGETS) {
  const schemaPath = fileURLToPath(new URL(`../../${target.schema}`, import.meta.url));
  const outPath = fileURLToPath(new URL(`../src/generated/${target.out}`, import.meta.url));

  // json-schema-to-zod does not follow $ref; the schemas have no cycles, so inline everything.
  const schema = await $RefParser.dereference(schemaPath);
  delete schema.$defs;
  stripConstraintOnlyAnyOf(schema);

  const body = jsonSchemaToZod(schema, { module: "esm", name: target.name, type: target.type });
  const header =
    `// Generated by \`pnpm codegen\` from packages/shared/${target.schema}. Do not edit.\n` +
    "// For types and parsing only; server-side validators in vp_shared are authoritative.\n";
  await writeFile(outPath, await format(header + body, { parser: "typescript", printWidth: 100 }));
}
